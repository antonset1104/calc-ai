/**
 * Mengambil teks terjemahan dengan fallback cerdas: lang -> en -> id -> string kosong
 */
export function t(obj, lang = 'id') {
  if (!obj) return '';
  if (typeof obj === 'string') return obj;
  return obj[lang] || obj.en || obj.id || Object.values(obj)[0] || '';
}

